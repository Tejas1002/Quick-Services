<?php

namespace App\Providers;

use Illuminate\Auth\Events\Login; // Import the Login event
use Illuminate\Auth\Events\Registered; // Import the Registered event
use Illuminate\Auth\Listeners\SendEmailVerificationNotification; // Import the default verification listener
use App\Listeners\SendLoginNotification; // Import your custom login listener
use Illuminate\Foundation\Support\Providers\EventServiceProvider as ServiceProvider;

class EventServiceProvider extends ServiceProvider
{
    /**
     * The event to listener mappings for the application.
     *
     * @var array<class-string, array<int, class-string>>
     */
    protected $listen = [
        Registered::class => [
            SendEmailVerificationNotification::class,
        ],
        Login::class => [
            SendLoginNotification::class,
        ],
    ];

    /**
     * Register any events for your application.
     *
     * @return void
     */
    public function boot()
    {
        //
    }

    /**
     * Determine if events and listeners should be automatically discovered.
     *
     * @return bool
     */
    public function shouldDiscoverEvents()
    {
        return false;
    }
}
